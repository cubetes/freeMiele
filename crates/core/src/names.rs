//! Programme and phase names for Miele appliances, by device type and code.
//!
//! Source: Home Assistant's Miele integration (Apache-2.0),
//! <https://github.com/home-assistant/core>, homeassistant/components/miele/const.py
//! (PROGRAM_IDS and PROGRAM_PHASE) with the English names from strings.json,
//! at commit 58b268badefdd49f7a229ecd1a67460389e6254e.
//! Miele's API sends no names for these codes. The names are unconfirmed unless listed in `CONFIRMED`
//! below. An empty name means "not running" or "no programme": nothing to show.

type Table = &'static [(&'static str, &'static [i64])];

fn find(table: Table, code: i64) -> Option<&'static str> {
    table
        .iter()
        .find(|(_, codes)| codes.contains(&code))
        .map(|(name, _)| *name)
}

/// Programme names seen on a real machine with a matching display, as `(type, code, name)`.
/// Add one only with the model it was confirmed on.
const CONFIRMED: &[(i64, i64, &str)] = &[
    // Coffee machine, CM 6160. Phase 4352 = not running was seen there too; it has no name to show.
    (17, 24753, "Degreasing the brew unit"),
];

pub fn confirmed_name(kind: i64, code: i64) -> Option<&'static str> {
    CONFIRMED
        .iter()
        .find(|c| (c.0, c.1) == (kind, code))
        .map(|c| c.2)
}

